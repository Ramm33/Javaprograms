package com.JourneyOfLearningJavaIn100Days;
import java.util.*;
public class Array29 {

	public static void main(String[] args) {
				System.out.println("Main method started");
				int n = 4;
				for (int i = 1; i <= n; i++) {
					for (int j = 1; j <= n ; j++) {
						System.out.print(" ");
					}
					for (int k = 1; k <= 2; k++) {
						System.out.print("*");
					}
					System.out.println();

				}

			}

	
	}

